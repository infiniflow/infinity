def _compose(line: str) -> str:
    """unicodedata.normalize("NFC", line), except that the code points of
    _NFC_PROTECTED stay as they are and nothing composes across them.

    Combining marks are not word characters, so the NFD of 'tiếng' would be
    cut into 'tie ng'. Precomposed text (U+212A KELVIN SIGN, the CJK
    compatibility ideographs, U+FB2A) keeps its code points, as it did before
    NFC. The rest holds only code points assigned in Unicode 13.0.0, whose
    NFC form Unicode keeps stable, so every Python version composes it alike.
    The C++ analyzer and its Rust port compose the same way, with the tables
    of tools/generate_unicode_nfc.py.
    """
    if unicodedata.is_normalized("NFC", line):
        return line
    # split() puts the protected runs, the regex group, at the odd indexes.
    return "".join(
        part if i % 2 else _undo_dotted_i(unicodedata.normalize("NFC", part))
        for i, part in enumerate(_NFC_PROTECTED.split(line))
    )


def _undo_dotted_i(text: str) -> str:
    """Turn each U+0130 that NFC composed from I + U+0307 back into I, with
    U+0307 among the marks after it in canonical order. Python lowercases
    U+0130 to i + U+0307 and the C++ analyzer keeps it, so _compose() does not
    form it; U+0130 typed as such is protected and never reaches this."""
    start = text.find("\u0130")
    if start == -1:
        return text
    out = []
    while start != -1:
        end = start + 1
        while end < len(text) and unicodedata.combining(text[end]):
            end += 1
        marks = sorted("\u0307" + text[start + 1 : end], key=unicodedata.combining)
        out.append(text[:start] + "I" + "".join(marks))
        text = text[end:]
        start = text.find("\u0130")
    out.append(text)
    return "".join(out)


