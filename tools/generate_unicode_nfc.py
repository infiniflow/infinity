"""Generate the NFC tables of the RAG tokenizer from Python's unicodedata.

rag_tokenizer.py composes its input with _compose(): unicodedata.normalize
("NFC") on everything but the protected code points, which it keeps as they
are and which nothing composes across. They are the Full_Composition_Exclusion
code points, so precomposed text (singletons such as U+212A KELVIN SIGN or the
CJK compatibility ideographs, the script-specific exclusions such as U+0958)
tokenizes as it did before NFC, and the code points not assigned in Unicode
13.0, the Unicode version of Python 3.10. Unicode keeps the NFC form of
assigned code points stable, so _compose() gives the same result on every
Python version from 3.10 on.

The C++ analyzer has no Unicode normalization library, so it and its Rust port
compose with the tables this script writes. The protected code points are left
out of them: a protected code point is a boundary, never decomposes and never
composes.

    src/common/analyzer/unicode_nfc_data.h
    rust_engine/crates/analyzer/src/unicode_nfc_data.rs
    python/infinity_sdk/infinity/rag_tokenizer.py, between the BEGIN and END
    lines of _compose()

It runs on Python 3.13, whose unicodedata is Unicode 15.1.0, the version the
tables are pinned to, and reads the code points assigned in Unicode 13.0 from
Python 3.10 through uv:

    uv run tools/generate_unicode_nfc.py

With --cases it writes nothing and prints the cases the C++ and Rust NFC tests
check against the _compose() in rag_tokenizer.py instead; that needs Python
3.13 only.
"""

