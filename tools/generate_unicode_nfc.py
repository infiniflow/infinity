GENERATED = """\
{c} Generated by tools/generate_unicode_nfc.py from Python's unicodedata
{c} (Unicode {version}). Do not edit; regenerate with
{c}   uv run tools/generate_unicode_nfc.py
"""

# Hangul syllables compose and decompose algorithmically; the code does that,
# the tables leave them out.
HANGUL_V = range(0x1161, 0x1176)
HANGUL_T = range(0x11A8, 0x11C3)


def require(condition, message):
    if not condition:
        sys.exit(message)


def canonical_decomposition(c):
    fields = unicodedata.decomposition(c).split()
    if not fields or fields[0].startswith("<"):
        return None
    return [int(f, 16) for f in fields]


def build_tables():
    decompositions = []  # (cp, first, second or 0), one level
    compositions = []  # (first, second, primary composite)
    for cp in range(0x110000):
        d = canonical_decomposition(chr(cp))
        if d is None:
            continue
        require(len(d) in (1, 2), f"U+{cp:04X} decomposes to {len(d)} code points")
        decompositions.append((cp, d[0], d[1] if len(d) == 2 else 0))
        if unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            require(
                len(d) == 2 and unicodedata.combining(chr(cp)) == 0,
                f"U+{cp:04X} is a primary composite but not a starter pair",
            )
            compositions.append((d[0], d[1], cp))
    compositions.sort()

    # NFC_Quick_Check: No for a decomposable code point that is not a primary
    # composite, Maybe for the second code point of a composition, Yes else.
    primary = {cp for _, _, cp in compositions}
    no = {cp for cp, _, _ in decompositions} - primary
    maybe = {second for _, second, _ in compositions} | set(HANGUL_V) | set(HANGUL_T)
    require(not no & maybe, "a code point is both NFC_QC=No and Maybe")

    # Code points that are not NFC boundaries (ccc != 0 or NFC_Quick_Check !=
    # Yes) as ranges of equal (ccc, quick check is Yes).
    non_boundary = []
    for cp in range(0x110000):
        ccc = unicodedata.combining(chr(cp))
        if ccc == 0 and cp not in no and cp not in maybe:
            continue
        props = (ccc, cp not in no and cp not in maybe)
        last = non_boundary[-1] if non_boundary else None
        if last and last[1] == cp - 1 and last[2:] == props:
            non_boundary[-1] = (last[0], cp, *props)
        else:
            non_boundary.append((cp, cp, *props))
    # Every code point below U+0300 is a boundary: ASCII never reaches a table.
    require(non_boundary[0][0] == 0x300, "a code point below U+0300 is not a boundary")
    return non_boundary, decompositions, compositions


def rows(entries, per_line, indent):
    lines = []
    for i in range(0, len(entries), per_line):
        lines.append(indent + " ".join(entries[i : i + per_line]))
    return "\n".join(lines)


def cpp_header(non_boundary, decompositions, compositions):
    def cp(v):
        return f"0x{v:04X}"

    nb = [
        f"{{{cp(a)}, {cp(b)}, {ccc}, {str(yes).lower()}}},"
        for a, b, ccc, yes in non_boundary
    ]
    dec = [f"{{{cp(a)}, {cp(b)}, {cp(c)}}}," for a, b, c in decompositions]
    comp = [f"{{{cp(a)}, {cp(b)}, {cp(c)}}}," for a, b, c in compositions]
    return f"""\
{LICENSE.format(c="//")}
{GENERATED.format(c="//", version=UNICODE_VERSION)}
#pragma once

#include <cstdint>

namespace infinity {{

// Code points first..last have canonical combining class ccc, and
// NFC_Quick_Check=Yes when quick_check_yes is set.
struct NFCRange {{
    char32_t first;
    char32_t last;
    uint8_t ccc;
    bool quick_check_yes;
}};

// cp decomposes to first (and second unless it is 0), one level deep.
struct NFCDecomposition {{
    char32_t cp;
    char32_t first;
    char32_t second;
}};

// first + second compose to the primary composite.
struct NFCComposition {{
    char32_t first;
    char32_t second;
    char32_t composite;
}};

// Every code point that is not an NFC boundary: ccc != 0 or
// NFC_Quick_Check != Yes. Sorted by first.
inline constexpr NFCRange NFC_NON_BOUNDARY[] = {{
    // clang-format off
{rows(nb, 4, "    ")}
    // clang-format on
}};

// The canonical decompositions, Hangul syllables excepted. Sorted by cp.
inline constexpr NFCDecomposition NFC_DECOMPOSITIONS[] = {{
    // clang-format off
{rows(dec, 5, "    ")}
    // clang-format on
}};

// The primary composites, Hangul syllables excepted. Sorted by first, second.
inline constexpr NFCComposition NFC_COMPOSITIONS[] = {{
    // clang-format off
{rows(comp, 5, "    ")}
    // clang-format on
}};

}} // namespace infinity
"""


def rust_module(non_boundary, decompositions, compositions):
    def ch(v):
        return f"'\\u{{{v:04X}}}'"

    nb = [
        f"({ch(a)}, {ch(b)}, {ccc}, {str(yes).lower()}),"
        for a, b, ccc, yes in non_boundary
    ]
    dec = [f"({ch(a)}, {ch(b)}, {ch(c)})," for a, b, c in decompositions]
    comp = [f"({ch(a)}, {ch(b)}, {ch(c)})," for a, b, c in compositions]
    return f"""\
{LICENSE.format(c="//")}
{GENERATED.format(c="//", version=UNICODE_VERSION)}
//! C++: `unicode_nfc_data.h` — the same tables, from the same generator.

/// C++: `NFC_NON_BOUNDARY` — (first, last, ccc, quick_check_yes) for every
/// code point that is not an NFC boundary: ccc != 0 or NFC_Quick_Check != Yes.
#[rustfmt::skip]
pub(crate) static NFC_NON_BOUNDARY: [(char, char, u8, bool); {len(nb)}] = [
{rows(nb, 3, "    ")}
];

/// C++: `NFC_DECOMPOSITIONS` — (cp, first, second), one level deep; second is
/// '\\0' for a singleton. Hangul syllables are left out.
#[rustfmt::skip]
pub(crate) static NFC_DECOMPOSITIONS: [(char, char, char); {len(dec)}] = [
{rows(dec, 3, "    ")}
];

/// C++: `NFC_COMPOSITIONS` — (first, second, primary composite), sorted by
/// first, second. Hangul syllables are left out.
#[rustfmt::skip]
pub(crate) static NFC_COMPOSITIONS: [(char, char, char); {len(comp)}] = [
{rows(comp, 3, "    ")}
];
"""


def print_cases():
    """One "input;NFC" line per case, code points in hex: every code point with
    a canonical decomposition, as itself and decomposed; every ordered pair of
    two Vietnamese marks on a vowel; the precomposed Vietnamese vowels with a
    tone mark; Hangul syllables, decomposed and partly composed; U+0344, U+0F73
    and U+0958, which NFC does not compose back."""
    cases = []
    for cp in range(0x110000):
        if canonical_decomposition(chr(cp)):
            cases += [chr(cp), unicodedata.normalize("NFD", chr(cp))]
    marks = "\u0300\u0301\u0302\u0303\u0306\u0309\u0323\u031b"
    for base in "aeiouyAEIOUY":
        for m1, m2 in itertools.permutations(marks, 2):
            cases.append(base + m1 + m2)
    vowels = "\u00e2\u00ea\u00f4\u0103\u01a1\u01b0\u00c2\u00ca\u00d4\u0102\u01a0\u01af"
    for base in vowels:
        for tone in "\u0300\u0301\u0303\u0309\u0323":
            cases.append(base + tone)
    for s in "\uac00\uac01\ud7a3":
        cases += [s, unicodedata.normalize("NFD", s)]
    cases += [
        "\uac00\u11a8",
        "\uac01\u11a8",
        "\u1100\u11a8",
        "\u0344",
        "\u0f73",
        "\u0958",
    ]
    for s in cases:
        nfc = unicodedata.normalize("NFC", s)
        print(";".join(" ".join(f"{ord(c):X}" for c in t) for t in (s, nfc)))


def main():
    parser = argparse.ArgumentParser(
        description="Generate the NFC tables of the RAG tokenizer."
    )
    parser.add_argument(
        "--cases",
        action="store_true",
        help='print the cases of the NFC tests ("input;NFC" in hex) instead',
    )
    args = parser.parse_args()
    require(
        unicodedata.unidata_version == UNICODE_VERSION,
        f"run with Python 3.13 (Unicode {UNICODE_VERSION}), not Unicode {unicodedata.unidata_version}",
    )
    if args.cases:
        print_cases()
        return
    tables = build_tables()
    CPP_PATH.write_text(cpp_header(*tables), encoding="utf-8")
    RUST_PATH.write_text(rust_module(*tables), encoding="utf-8")


if __name__ == "__main__":
    main()
