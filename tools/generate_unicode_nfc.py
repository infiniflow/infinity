import itertools
import pathlib
import sys
import unicodedata

UNICODE_VERSION = "15.1.0"
ROOT = pathlib.Path(__file__).resolve().parent.parent
CPP_PATH = ROOT / "src/common/analyzer/unicode_nfc_data.h"
RUST_PATH = ROOT / "rust_engine/crates/analyzer/src/unicode_nfc_data.rs"

