# Composites that are left out of composition although NFC forms them. U+0130:
# Python's str.lower() turns it into i + U+0307, while the C++ and Rust
# lowercasing keep it, so composing I + U+0307 would make the engines disagree
# on decomposed text they tokenized alike before. It is protected, so typed as
# U+0130 it stays as it is, and _compose() turns every U+0130 that NFC forms
# back into I + U+0307.
NOT_COMPOSED = {0x0130}
DOT_ABOVE = 0x0307

# Hangul syllables compose and decompose algorithmically; the code does that,
# the tables leave them out.
HANGUL_V = range(0x1161, 0x1176)
HANGUL_T = range(0x11A8, 0x11C3)


def require(condition, message):
    if not condition:
        sys.exit(message)


def canonical_decomposition(c):
    fields = unicodedata.decomposition(c).split()
    if not fields or fields[0].startswith("<"):
        return None
    return [int(f, 16) for f in fields]


# Prints the ranges of code points that are not assigned, one "first last" line
# each, after the Unicode version.
UNASSIGNED_SCRIPT = """\
import itertools, unicodedata
print(unicodedata.unidata_version)
for cn, run in itertools.groupby(range(0x110000), lambda cp: unicodedata.category(chr(cp)) == "Cn"):
    if cn:
        run = list(run)
        print(run[0], run[-1])
"""


def protected_code_points():
    """The code points _compose() keeps: Full_Composition_Exclusion and the
    code points not assigned in Unicode 13.0."""
    try:
        result = subprocess.run(
            ["uv", "run", "--no-project", "--python", STABLE_PYTHON]
            + ["python", "-I", "-c", UNASSIGNED_SCRIPT],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit(f"cannot run Python {STABLE_PYTHON} through uv: {e}")
    version, *lines = result.stdout.splitlines()
    require(
        version == STABLE_UNICODE_VERSION,
        f"Python {STABLE_PYTHON} has Unicode {version}, not {STABLE_UNICODE_VERSION}",
    )
    protected = {
        cp for cp in range(0x110000) if unicodedata.normalize("NFC", chr(cp)) != chr(cp)
    }
    for line in lines:
        first, last = map(int, line.split())
        protected.update(range(first, last + 1))
    return protected | NOT_COMPOSED


def build_tables(protected):
    decompositions = []  # (cp, first, second), one level
    compositions = []  # (first, second, primary composite)
    for cp in range(0x110000):
        d = canonical_decomposition(chr(cp))
        if d is None or cp in protected:
            continue
        # Every code point NFC does not keep (Full_Composition_Exclusion) is
        # protected, so the ones left are primary composites.
        require(
            len(d) == 2 and unicodedata.combining(chr(cp)) == 0,
            f"U+{cp:04X} is a primary composite but not a starter pair",
        )
        # Decomposing and composing again never reaches a protected code point.
        require(
            not protected & set(d),
            f"U+{cp:04X} decomposes to a protected code point",
        )
        decompositions.append((cp, d[0], d[1]))
        compositions.append((d[0], d[1], cp))
    compositions.sort()
    # _compose() undoes I + U+0307 -> U+0130 by putting U+0307 back among the
    # marks after I. That equals leaving the pair out of the tables only while
    # nothing composes with U+0130, and nothing after U+0307 composes with I:
    # U+0307 blocks every mark of a class up to its own.
    i_dot = canonical_decomposition(chr(0x0130))
    require(i_dot == [ord("I"), DOT_ABOVE], "U+0130 is no longer I + U+0307")
    require(
        all(
            canonical_decomposition(chr(cp)) is None
            or canonical_decomposition(chr(cp))[0] not in NOT_COMPOSED
            for cp in range(0x110000)
        ),
        "a composite starts with U+0130",
    )
    require(
        all(
            unicodedata.combining(chr(second)) <= unicodedata.combining(chr(DOT_ABOVE))
            for first, second, _ in compositions
            if first == ord("I")
        ),
        "a mark of a class above U+0307 composes with I",
    )

    # NFC_Quick_Check: the protected code points are all the No ones, so for
    # the others it is Maybe for the second code point of a composition and
    # Yes else.
    maybe = {second for _, second, _ in compositions} | set(HANGUL_V) | set(HANGUL_T)

    # Code points that are not NFC boundaries (ccc != 0 or NFC_Quick_Check !=
    # Yes) as ranges of equal (ccc, quick check is Yes). A protected code point
    # is a boundary.
    non_boundary = []
    for cp in range(0x110000):
        ccc = unicodedata.combining(chr(cp))
        if cp in protected or (ccc == 0 and cp not in maybe):
            continue
        props = (ccc, cp not in maybe)
        last = non_boundary[-1] if non_boundary else None
        if last and last[1] == cp - 1 and last[2:] == props:
            non_boundary[-1] = (last[0], cp, *props)
        else:
            non_boundary.append((cp, cp, *props))
    # Every code point below U+0300 is a boundary: ASCII never reaches a table.
    require(non_boundary[0][0] == 0x300, "a code point below U+0300 is not a boundary")
    return non_boundary, decompositions, compositions


def rows(entries, per_line, indent):
    lines = []
    for i in range(0, len(entries), per_line):
        lines.append(indent + " ".join(entries[i : i + per_line]))
    return "\n".join(lines)


def cpp_header(non_boundary, decompositions, compositions):
    def cp(v):
        return f"0x{v:04X}"

    nb = [
        f"{{{cp(a)}, {cp(b)}, {ccc}, {str(yes).lower()}}},"
        for a, b, ccc, yes in non_boundary
    ]
    dec = [f"{{{cp(a)}, {cp(b)}, {cp(c)}}}," for a, b, c in decompositions]
    comp = [f"{{{cp(a)}, {cp(b)}, {cp(c)}}}," for a, b, c in compositions]
    return f"""\
{LICENSE.format(c="//")}
{GENERATED.format(c="//", version=UNICODE_VERSION)}
#pragma once

#include <cstdint>

namespace infinity {{

// Code points first..last have canonical combining class ccc, and
// NFC_Quick_Check=Yes when quick_check_yes is set.
struct NFCRange {{
    char32_t first;
    char32_t last;
    uint8_t ccc;
    bool quick_check_yes;
}};

// cp decomposes to first and second, one level deep.
struct NFCDecomposition {{
    char32_t cp;
    char32_t first;
    char32_t second;
}};

// first + second compose to the primary composite.
struct NFCComposition {{
    char32_t first;
    char32_t second;
    char32_t composite;
}};

// The protected code points (Full_Composition_Exclusion and the code points not
// assigned in Unicode 13.0, see the generator) are in no table: they are
// boundaries, never decompose and never compose.

// Every code point that is not an NFC boundary: ccc != 0 or
// NFC_Quick_Check != Yes. Sorted by first.
inline constexpr NFCRange NFC_NON_BOUNDARY[] = {{
    // clang-format off
{rows(nb, 4, "    ")}
    // clang-format on
}};

// The canonical decompositions of the primary composites, Hangul syllables
// excepted. Sorted by cp.
inline constexpr NFCDecomposition NFC_DECOMPOSITIONS[] = {{
    // clang-format off
{rows(dec, 5, "    ")}
    // clang-format on
}};

// The primary composites, Hangul syllables excepted. Sorted by first, second.
inline constexpr NFCComposition NFC_COMPOSITIONS[] = {{
    // clang-format off
{rows(comp, 5, "    ")}
    // clang-format on
}};

}} // namespace infinity
"""


def rust_module(non_boundary, decompositions, compositions):
    def ch(v):
        return f"'\\u{{{v:04X}}}'"

    nb = [
        f"({ch(a)}, {ch(b)}, {ccc}, {str(yes).lower()}),"
        for a, b, ccc, yes in non_boundary
    ]
    dec = [f"({ch(a)}, {ch(b)}, {ch(c)})," for a, b, c in decompositions]
    comp = [f"({ch(a)}, {ch(b)}, {ch(c)})," for a, b, c in compositions]
    return f"""\
{LICENSE.format(c="//")}
{GENERATED.format(c="//", version=UNICODE_VERSION)}
//! C++: `unicode_nfc_data.h` — the same tables, from the same generator.
//!
//! The protected code points (Full_Composition_Exclusion and the code points
//! not assigned in Unicode 13.0, see the generator) are in no table: they are
//! boundaries, never decompose and never compose.

/// C++: `NFC_NON_BOUNDARY` — (first, last, ccc, quick_check_yes) for every
/// code point that is not an NFC boundary: ccc != 0 or NFC_Quick_Check != Yes.
#[rustfmt::skip]
pub(crate) static NFC_NON_BOUNDARY: [(char, char, u8, bool); {len(nb)}] = [
{rows(nb, 3, "    ")}
];

/// C++: `NFC_DECOMPOSITIONS` — (cp, first, second) for the primary composites,
/// one level deep. Hangul syllables are left out.
#[rustfmt::skip]
pub(crate) static NFC_DECOMPOSITIONS: [(char, char, char); {len(dec)}] = [
{rows(dec, 3, "    ")}
];

/// C++: `NFC_COMPOSITIONS` — (first, second, primary composite), sorted by
/// first, second. Hangul syllables are left out.
#[rustfmt::skip]
pub(crate) static NFC_COMPOSITIONS: [(char, char, char); {len(comp)}] = [
{rows(comp, 3, "    ")}
];
"""


def python_block(protected):
    """The _NFC_PROTECTED regex and _compose() of rag_tokenizer.py."""
    ranges = []
    for cp in sorted(protected):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])

    def esc(cp):
        return f"\\u{cp:04x}" if cp < 0x10000 else f"\\U{cp:08x}"

    items = [esc(a) if a == b else f"{esc(a)}-{esc(b)}" for a, b in ranges]
    lines, line = [], ""
    for item in items:
        if len(line) + len(item) > 78:
            lines.append(f'    "{line}"')
            line = ""
        line += item
    lines.append(f'    "{line}"')
    class_lines = "\n".join(lines)
    return f'''\
{BLOCK_BEGIN} from Python's unicodedata
# (Unicode {UNICODE_VERSION} and {STABLE_UNICODE_VERSION}). Do not edit; regenerate with
#   uv run tools/generate_unicode_nfc.py
#
# The code points _compose() keeps as they are: Full_Composition_Exclusion
# (Unicode {UNICODE_VERSION}), which NFC would replace, and every code point not
# assigned in Unicode {STABLE_UNICODE_VERSION}, the unicodedata of Python {STABLE_PYTHON}.
_NFC_PROTECTED = re.compile(
    "(["
{class_lines}
    "]+)"
)


def _compose(line: str) -> str:
    """unicodedata.normalize("NFC", line), except that the code points of
    _NFC_PROTECTED stay as they are and nothing composes across them.

    Combining marks are not word characters, so the NFD of 'tiếng' would be
    cut into 'tie ng'. Precomposed text (U+212A KELVIN SIGN, the CJK
    compatibility ideographs, U+FB2A) keeps its code points, as it did before
    NFC. The rest holds only code points assigned in Unicode {STABLE_UNICODE_VERSION}, whose
    NFC form Unicode keeps stable, so every Python version composes it alike.
    The C++ analyzer and its Rust port compose the same way, with the tables
    of tools/generate_unicode_nfc.py.
    """
    if unicodedata.is_normalized("NFC", line):
        return line
    # split() puts the protected runs, the regex group, at the odd indexes.
    return "".join(
        part if i % 2 else _undo_dotted_i(unicodedata.normalize("NFC", part))
        for i, part in enumerate(_NFC_PROTECTED.split(line))
    )


def _undo_dotted_i(text: str) -> str:
    """Turn each U+0130 that NFC composed from I + U+0307 back into I, with
    U+0307 among the marks after it in canonical order. Python lowercases
    U+0130 to i + U+0307 and the C++ analyzer keeps it, so _compose() does not
    form it; U+0130 typed as such is protected and never reaches this."""
    start = text.find("\\u0130")
    if start == -1:
        return text
    out = []
    while start != -1:
        end = start + 1
        while end < len(text) and unicodedata.combining(text[end]):
            end += 1
        marks = sorted("\\u0307" + text[start + 1 : end], key=unicodedata.combining)
        out.append(text[:start] + "I" + "".join(marks))
        text = text[end:]
        start = text.find("\\u0130")
    out.append(text)
    return "".join(out)


{BLOCK_END}
'''


def split_python_source():
    """rag_tokenizer.py as (before, generated block, after)."""
    source = PYTHON_PATH.read_text(encoding="utf-8")
    require(
        source.count(BLOCK_BEGIN) == 1 and source.count(BLOCK_END) == 1,
        f"{PYTHON_PATH} needs one {BLOCK_BEGIN!r} and one {BLOCK_END!r} line",
    )
    begin = source.index(BLOCK_BEGIN)
    end = source.index("\n", source.index(BLOCK_END)) + 1
    return source[:begin], source[begin:end], source[end:]


def load_compose():
    """_compose() of rag_tokenizer.py, without importing its dependencies."""
    namespace = {"re": re, "unicodedata": unicodedata}
    exec(split_python_source()[1], namespace)  # noqa: S102 - this repository's code
    return namespace["_compose"]


def print_cases():
    """One "input;expected" line per case, code points in hex, expected being
    _compose() of rag_tokenizer.py: every code point with a canonical
    decomposition, as itself and decomposed; every ordered pair of two
    Vietnamese marks on a vowel; the precomposed Vietnamese vowels with a tone
    mark; Hangul syllables, decomposed and partly composed; protected code
    points alone, between letters and next to combining marks; code points
    assigned after Unicode 13.0, some of which compose in later versions."""
    cases = []
    for cp in range(0x110000):
        if canonical_decomposition(chr(cp)):
            cases += [chr(cp), unicodedata.normalize("NFD", chr(cp))]
    marks = "̛̣̀́̂̃̆̉"
    for base in "aeiouyAEIOUY":
        for m1, m2 in itertools.permutations(marks, 2):
            cases.append(base + m1 + m2)
    vowels = "âêôăơưÂÊÔĂƠƯ"
    for base in vowels:
        for tone in "̣̀́̃̉":
            cases.append(base + tone)
    for s in "가각힣":
        cases += [s, unicodedata.normalize("NFD", s)]
    cases += [
        "각",
        "각ᆨ",
        "ᄀᆨ",
        # Full_Composition_Exclusion: non-starter decompositions, a
        # script-specific exclusion and singletons.
        "̈́",
        "ཱི",
        "क़",
        "क़़",
        "שׁלום",
        "Km",
        "濾",
        # Marks before, after and around protected code points.
        "éक़́",
        "à̖́",
        "̖̀",
        "ẹ̈́",
        "ᄀक़ᅡ",
        "क़̈́",
        # I + U+0307 does not compose (NOT_COMPOSED), with marks of lower and
        # higher classes around it; U+0130 typed as such stays.
        "abI\u0307cd",
        "I\u0307",
        "I\u0316\u0307",
        "I\u0307\u0316",
        "I\u0307\u0301",
        "I\u0307\u0315",
        "I\u0323\u0307",
        "I\u0307\u0323",
        "I\u0301\u0307",
        "\u0130",
        "\u0130\u0323",
        "\u0130\u0307\u0316",
        # Marks typed out of canonical order, of the same length once ordered.
        "x॒́",
        "+̖́",
        "بَّ",
        # Assigned after Unicode 13.0: a mark of 14.0 (U+0897), the pairs that
        # compose in 16.0 (U+105D2 U+0307, U+11382 U+113C9, U+1611E U+1611E),
        # and a 13.0 letter with marks around a 15.0 mark (U+1E4EC).
        "eࢗ́",
        "\U000105d2̇",
        "\U00011382\U000113c9",
        "\U0001611e\U0001611e",
        "é\U0001e4ec̣",
        "\U0001e4eć̖",
    ]
    compose = load_compose()
    for s in cases:
        expected = compose(s)
        print(";".join(" ".join(f"{ord(c):X}" for c in t) for t in (s, expected)))


def main():
    parser = argparse.ArgumentParser(
        description="Generate the NFC tables of the RAG tokenizer."
    )
    parser.add_argument(
        "--cases",
        action="store_true",
        help='print the cases of the NFC tests ("input;expected" in hex) instead',
    )
    args = parser.parse_args()
    require(
        unicodedata.unidata_version == UNICODE_VERSION,
        f"run with Python 3.13 (Unicode {UNICODE_VERSION}), not Unicode {unicodedata.unidata_version}",
    )
    if args.cases:
        print_cases()
        return
    protected = protected_code_points()
    tables = build_tables(protected)
    before, _, after = split_python_source()
    CPP_PATH.write_text(cpp_header(*tables), encoding="utf-8")
    RUST_PATH.write_text(rust_module(*tables), encoding="utf-8")
    PYTHON_PATH.write_text(before + python_block(protected) + after, encoding="utf-8")


if __name__ == "__main__":
    main()
